export function applyCalibrationToParams(params, cal) {
  const scales = {
    tone: cal?.toneScale ?? 1.0,
    wb: cal?.wbScale ?? 1.0,
    chroma: cal?.chromaScale ?? 1.0,
  };
  const src = params || {};
  const out = { ...src };

  for (const spec of PARAM_SCHEMA) {
    const scale = scales[spec.calibrated] ?? 1.0;
    const raw = src[spec.key] ?? spec.default;
    const scaled = spec.default + (raw - spec.default) * scale;
    const clamped = Math.max(spec.uiMin, Math.min(spec.uiMax, scaled));
    out[spec.key] = Math.round(clamped * 100) / 100;
  }
  return out;
}
