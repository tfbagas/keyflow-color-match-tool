def get_svg_code(name, color="#91A69A", stroke_width=2.0):
    inner = SVG_ICONS.get(name, SVG_ICONS["info"])
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">{inner}</svg>'

def get_pixmap(name, color="#91A69A", size=20, stroke_width=2.0):
    svg = get_svg_code(name, color, stroke_width)
    renderer = QSvgRenderer(QByteArray(svg.encode('utf-8')))
    pix = QPixmap(size, size)
    pix.fill(QColor(0, 0, 0, 0))
    painter = QPainter(pix)
    renderer.render(painter)
    painter.end()
    return pix

def get_icon(name, normal_color="#91A69A", active_color="#00E987", size=20, stroke_width=2.0):
    icon = QIcon()
    pix_normal = get_pixmap(name, normal_color, size, stroke_width)
    pix_active = get_pixmap(name, active_color, size, stroke_width)
    icon.addPixmap(pix_normal, QIcon.Normal)
    icon.addPixmap(pix_active, QIcon.Active)
    icon.addPixmap(pix_active, QIcon.Selected)
    return icon
