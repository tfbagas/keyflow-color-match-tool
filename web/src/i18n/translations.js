export function translateStatusText(statusText, lang = "en") {
  const raw = String(statusText || "Ready").trim();
  if (lang !== "id") return raw.toUpperCase();

  const lower = raw.toLowerCase();
  const dict = TRANSLATIONS.id.status;
  if (lower === "ready") return dict.ready;
  if (lower === "analyzing..." || lower.startsWith("analyzing")) return dict.analyzing;
  if (lower === "matched") return dict.matched;
  if (lower === "exported!" || lower === "exported") return dict.exported;
  if (lower === "calibrated") return dict.calibrated;
  if (lower === "reset") return dict.reset;
  if (lower === "undo") return dict.undo;
  if (lower === "redo") return dict.redo;
  if (lower === "error") return dict.error;
  if (lower === "import error") return dict.importError;
  if (lower === "export error" || lower === "video export error") return dict.exportError;
  if (lower === "video error") return dict.videoError;
  if (lower === "decode error") return dict.decodeError;
  if (lower === "invalid file") return dict.invalidFile;
  if (lower === "invalid image") return dict.invalidImage;
  if (lower === "video ready") return dict.videoReady;
  if (lower === "target ready") return dict.targetReady;
  if (lower === "loaded share") return dict.loadedShare;
  if (lower === "demo loaded") return dict.demoLoaded;
  if (lower === "restored session") return dict.restoredSession;
  if (lower === "applied look") return dict.appliedLook;
  if (lower === "shared!") return dict.shared;
  if (lower === "share error") return dict.shareError;
  if (lower === "export cancelled") return dict.exportCancelled;
  if (lower === "rendering video...") return dict.renderingVideo;
  if (lower === "exported video!") return dict.exportedVideo;
  if (lower === "exported pack!") return dict.exportedPack;
  if (lower === "packaging .zip...") return dict.packagingZip;
  if (lower === "matching current frame...") return dict.matchingCurrentFrame;
  if (lower === "preset imported") return dict.presetImported;
  if (lower === "direct preset conversion ready") return dict.directConversionReady;
  if (lower === "copied to b") return "DISALIN KE B";
  if (lower.startsWith("slot ")) return raw.toUpperCase();
  if (lower.startsWith("saved ")) return `${raw.slice(6).toUpperCase()} TERSIMPAN`;
  if (lower.startsWith("exported ")) return `${raw.slice(9).toUpperCase()} TEREKSPOR`;
  if (lower.startsWith("exporting")) return "MENGEKSPOR...";
  if (lower.startsWith("importing")) return "MENGIMPOR...";
  if (lower.startsWith("decoding")) return "MEMPROSES...";
  if (lower === "loading video...") return "MEMUAT VIDEO...";
  if (lower.startsWith("smart sampling")) return "SAMPLING VIDEO...";
  if (lower.startsWith("switching to")) return "MENGGANTI ENGINE...";
  if (lower.startsWith("auto-normalizing")) return "AUTO-NORMALIZE...";
  if (lower === "re-matching...") return "MENCOCOKKAN ULANG...";
  if (lower.startsWith("matching with")) return "MENCOCOKKAN LOG...";
  return raw.toUpperCase();
}